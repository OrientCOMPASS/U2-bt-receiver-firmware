#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen-vendor-mk.py -- generate the vendor prebuilt makefiles for KeenPlus U2.

Reads device/keenplus/u2/proprietary-files.txt (the curated blob list) and emits:

  vendor/keenplus/u2/Android.mk   prebuilt module definitions (BUILD_PREBUILT)
  vendor/keenplus/u2/blobs.mk     PRODUCT_PACKAGES += for those modules, plus a
                                  comment listing the non-module data files that
                                  device.mk must copy with PRODUCT_COPY_FILES.

Keeping these generated (rather than hand-written) means the module list can
never drift from proprietary-files.txt.  CI runs `--check` to fail the build if
the committed makefiles are stale.

The blobs themselves are NOT committed (see .gitignore); extract-files.sh pulls
them out of the baseline system image at build time.  Install-path details that
can only be confirmed against a real AOSP build (vendor vs system partition,
hw/ subdir, LOCAL_SHARED_LIBRARIES) are emitted with sensible defaults and
flagged in comments -- this repo cannot compile AOSP in CI (see patches/README).

Usage:
    gen-vendor-mk.py            # write the two files
    gen-vendor-mk.py --check     # regenerate in memory, diff, exit 1 if stale
    gen-vendor-mk.py --stdout    # print both files, write nothing
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import List, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
LIST_FILE = os.path.join(REPO_ROOT, "device/keenplus/u2/proprietary-files.txt")
VENDOR_DIR = os.path.join(REPO_ROOT, "vendor/keenplus/u2")
ANDROID_MK = os.path.join(VENDOR_DIR, "Android.mk")
BLOBS_MK = os.path.join(VENDOR_DIR, "blobs.mk")

HEADER = ("# GENERATED by scripts/gen-vendor-mk.py from "
          "device/keenplus/u2/proprietary-files.txt.\n"
          "# Do not edit by hand -- edit the list and re-run the generator "
          "(or `make` it in CI via --check).\n")


class Entry:
    __slots__ = ("path", "kind", "module", "relpath", "hw", "vendor")

    def __init__(self, path: str, kind: str, module: str, relpath: str,
                 hw: bool, vendor: bool) -> None:
        self.path = path        # original list line, e.g. vendor/lib/hw/foo.so
        self.kind = kind        # "lib" | "bin" | "data"
        self.module = module    # prebuilt module name ("" for data)
        self.relpath = relpath  # path under proprietary/, e.g. vendor/lib/hw/foo.so
        self.hw = hw            # lives in a /hw/ dir -> LOCAL_MODULE_RELATIVE_PATH
        self.vendor = vendor    # under vendor/ -> LOCAL_VENDOR_MODULE


def parse_list(text: str) -> List[str]:
    """Return the non-comment, non-blank entries of proprietary-files.txt."""
    out: List[str] = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def classify(path: str) -> Entry:
    """Decide whether a list entry is a prebuilt lib, a prebuilt bin, or data."""
    p = path.lstrip("/")
    base = os.path.basename(p)
    hw = "/hw/" in ("/" + p) or p.startswith("hw/")
    vendor = p.startswith("vendor/")

    if p.endswith(".so"):
        module = base[:-3]
        return Entry(path, "lib", module, p, hw, vendor)

    # Executables live under a bin/ directory and have no extension.
    if ("/bin/" in ("/" + p) or p.startswith("bin/")) and "." not in base:
        return Entry(path, "bin", base, p, hw, vendor)

    # Everything else (firmware, .cfg, .conf, .bin, .xml, directories) is data
    # copied via PRODUCT_COPY_FILES in device.mk -- not a prebuilt module.
    return Entry(path, "data", "", p, hw, vendor)


def build_entries(paths: List[str]) -> Tuple[List[Entry], List[Entry], List[Entry]]:
    libs = [classify(p) for p in paths]
    lib_e = [e for e in libs if e.kind == "lib"]
    bin_e = [e for e in libs if e.kind == "bin"]
    data_e = [e for e in libs if e.kind == "data"]
    return lib_e, bin_e, data_e


def gen_android_mk(lib_e: List[Entry], bin_e: List[Entry], data_e: List[Entry]) -> str:
    out: List[str] = [HEADER, "\n",
                      "LOCAL_PATH := $(call my-dir)\n", "\n",
                      "# ---- prebuilt 32-bit shared libraries (decision D2) ----\n",
                      "# LOCAL_SHARED_LIBRARIES is intentionally omitted: with\n",
                      "# BUILD_PREBUILT the loader resolves DT_NEEDED at runtime.\n",
                      "# If a real build reports an unresolved symbol, add the\n",
                      "# missing dependency to the module below (verify with\n",
                      "# `readelf -d proprietary/<path>`).\n\n"]
    for e in lib_e:
        out.append("include $(CLEAR_VARS)\n")
        out.append(f"LOCAL_MODULE := {e.module}\n")
        out.append("LOCAL_MODULE_CLASS := SHARED_LIBRARIES\n")
        out.append("LOCAL_MODULE_SUFFIX := .so\n")
        out.append(f"LOCAL_SRC_FILES := proprietary/{e.relpath}\n")
        out.append("LOCAL_MODULE_TAGS := optional\n")
        out.append("LOCAL_MULTILIB := 32\n")
        out.append("LOCAL_STRIP_MODULE :=\n")
        if e.vendor:
            out.append("LOCAL_VENDOR_MODULE := true\n")
        if e.hw:
            out.append("LOCAL_MODULE_RELATIVE_PATH := hw\n")
        out.append("include $(BUILD_PREBUILT)\n\n")

    out.append("# ---- prebuilt native executables ----\n\n")
    for e in bin_e:
        out.append("include $(CLEAR_VARS)\n")
        out.append(f"LOCAL_MODULE := {e.module}\n")
        out.append("LOCAL_MODULE_CLASS := EXECUTABLES\n")
        out.append(f"LOCAL_SRC_FILES := proprietary/{e.relpath}\n")
        out.append("LOCAL_MODULE_TAGS := optional\n")
        out.append("LOCAL_MULTILIB := 32\n")
        out.append("LOCAL_STRIP_MODULE :=\n")
        if e.vendor:
            out.append("LOCAL_VENDOR_MODULE := true\n")
        out.append("include $(BUILD_PREBUILT)\n\n")

    out.append("# ---- data files (NOT modules) ----\n")
    out.append("# The following list entries are firmware/config/data, installed\n")
    out.append("# via PRODUCT_COPY_FILES (see device.mk and blobs.mk), not as\n")
    out.append("# prebuilt modules:\n")
    for e in data_e:
        out.append(f"#   {e.relpath}\n")
    return "".join(out)


def gen_blobs_mk(lib_e: List[Entry], bin_e: List[Entry], data_e: List[Entry]) -> str:
    out: List[str] = [HEADER, "\n",
                      "# Included from device/keenplus/u2/device.mk.\n",
                      "# Lists every prebuilt module defined in vendor/keenplus/u2/Android.mk\n",
                      "# so the build installs the extracted HAL/library blobs.\n\n",
                      "PRODUCT_PACKAGES += \\\n"]
    mods = [e.module for e in lib_e] + [e.module for e in bin_e]
    for i, m in enumerate(mods):
        sep = " \\" if i < len(mods) - 1 else ""
        out.append(f"    {m}{sep}\n")
    out.append("\n# ---- data files still needing explicit PRODUCT_COPY_FILES ----\n")
    out.append("# (firmware / wifi / audio_param etc.; device.mk already copies the\n")
    out.append("#  MT6627 firmware -- confirm each of these is handled):\n")
    for e in data_e:
        out.append(f"#   {e.relpath}\n")
    return "".join(out)


def read(path: str) -> str:
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail (exit 1) if the committed makefiles are stale")
    ap.add_argument("--stdout", action="store_true",
                    help="print generated files, write nothing")
    args = ap.parse_args(argv)

    paths = parse_list(read(LIST_FILE))
    lib_e, bin_e, data_e = build_entries(paths)
    android = gen_android_mk(lib_e, bin_e, data_e)
    blobs = gen_blobs_mk(lib_e, bin_e, data_e)

    if args.stdout:
        sys.stdout.write("===== Android.mk =====\n" + android)
        sys.stdout.write("\n===== blobs.mk =====\n" + blobs)
        return 0

    if args.check:
        stale = []
        for path, want in ((ANDROID_MK, android), (BLOBS_MK, blobs)):
            have = read(path) if os.path.isfile(path) else None
            if have != want:
                stale.append(path)
        if stale:
            for s in stale:
                print(f"STALE: {os.path.relpath(s, REPO_ROOT)} "
                      f"(re-run: python3 scripts/gen-vendor-mk.py)")
            return 1
        print(f"gen-vendor-mk --check: OK "
              f"({len(lib_e)} libs, {len(bin_e)} bins, {len(data_e)} data)")
        return 0

    os.makedirs(VENDOR_DIR, exist_ok=True)
    with open(ANDROID_MK, "w", encoding="utf-8") as f:
        f.write(android)
    with open(BLOBS_MK, "w", encoding="utf-8") as f:
        f.write(blobs)
    print(f"wrote {os.path.relpath(ANDROID_MK, REPO_ROOT)} "
          f"({len(lib_e)} libs, {len(bin_e)} bins)")
    print(f"wrote {os.path.relpath(BLOBS_MK, REPO_ROOT)} "
          f"({len(lib_e) + len(bin_e)} PRODUCT_PACKAGES, {len(data_e)} data notes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
